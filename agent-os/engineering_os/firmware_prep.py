"""Deterministic Zephyr blinky preparation (Phase 6)."""

from __future__ import annotations

from typing import Any, Optional

# Minimal Zephyr application — deterministic, traceable, no codegen framework.
_BLINKY_CMAKE = """\
cmake_minimum_required(VERSION 3.20.0)
find_package(Zephyr REQUIRED HINTS $ENV{ZEPHYR_BASE})
project(pyra_blinky)
target_sources(app PRIVATE src/main.c)
"""

_BLINKY_CONF = """\
CONFIG_GPIO=y
"""

_BLINKY_MAIN = """\
#include <zephyr/kernel.h>
#include <zephyr/drivers/gpio.h>

#define LED0_NODE DT_ALIAS(led0)

#if !DT_NODE_EXISTS(LED0_NODE)
#error "No led0 alias in board DTS — cannot build blinky for this board"
#endif

static const struct gpio_dt_spec led = GPIO_DT_SPEC_GET(LED0_NODE, gpios);

int main(void)
{
        if (!gpio_is_ready_dt(&led)) {
                return 0;
        }
        gpio_pin_configure_dt(&led, GPIO_OUTPUT_ACTIVE);
        while (1) {
                gpio_pin_toggle_dt(&led);
                k_msleep(500);
        }
        return 0;
}
"""

_README = """\
# PYRA Zephyr blinky (Phase 6)

Deterministic scaffold prepared by Engineering OS.
Build via Device Broker L2 `west_build`.
Flashing is not performed in Phase 6.
"""


def blinky_file_set(*, board_id: str, zephyr_board: str) -> dict[str, str]:
    """Return relative path → content for a blinky app."""
    meta = (
        f"# Generated by PYRA Engineering OS\n"
        f"# board_id={board_id}\n"
        f"# zephyr_board={zephyr_board}\n"
        f"# phase=6\n"
    )
    return {
        "CMakeLists.txt": _BLINKY_CMAKE,
        "prj.conf": _BLINKY_CONF,
        "src/main.c": _BLINKY_MAIN,
        "README_PYRA.md": _README + "\n" + meta,
        "pyra_board_meta.txt": meta,
    }


def prepare_zephyr_blinky_via_broker(
    client: Any,
    *,
    project_id: str,
    workspace_path: str,
    board_id: str,
    zephyr_board: str,
    relative_root: str = "firmware/zephyr_blinky",
) -> dict[str, Any]:
    """
    Write blinky files through Broker L1 write_text_file into the project workspace.
    """
    if not project_id:
        raise ValueError("project_id required")
    if not zephyr_board:
        raise ValueError("zephyr_board required")
    files = blinky_file_set(board_id=board_id, zephyr_board=zephyr_board)
    written: list[str] = []
    errors: list[str] = []

    # Ensure directories
    for rel in (relative_root, f"{relative_root}/src"):
        r = client.call(
            "create_directory",
            {"path": f"{workspace_path.rstrip('/')}/{rel}"},
            principal="engineering_os",
            max_level="L1",
            project_id=project_id,
            client="engineering_os",
        )
        if not r.ok and "exists" not in (r.error or "").lower():
            # create_directory may fail if exists — continue if path usable
            if r.status == "denied":
                errors.append(r.error or "create_directory denied")
                return {
                    "ok": False,
                    "source_dir": None,
                    "files": [],
                    "errors": errors,
                    "board_id": board_id,
                    "zephyr_board": zephyr_board,
                }

    for rel, content in files.items():
        path = f"{workspace_path.rstrip('/')}/{relative_root}/{rel}"
        r = client.call(
            "write_text_file",
            {"path": path, "content": content, "overwrite": True},
            principal="engineering_os",
            max_level="L1",
            project_id=project_id,
            client="engineering_os",
        )
        if r.ok:
            written.append(path)
        else:
            errors.append(f"{rel}: {r.error}")

    source_dir = f"{workspace_path.rstrip('/')}/{relative_root}"
    return {
        "ok": not errors,
        "source_dir": source_dir if not errors else None,
        "files": written,
        "errors": errors,
        "board_id": board_id,
        "zephyr_board": zephyr_board,
        "relative_root": relative_root,
    }
